#!/usr/bin/env python3
"""Write the paper's pilot outcome figure (TikZ stacked bars) from results/agent-pilot/analysis.json."""
from __future__ import annotations

import collections
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "results/agent-pilot/analysis.json"
OUT = ROOT / "paper/usenix/fig-pilot-outcomes.tex"
MODEL = "claude-haiku-5-5"
OUTCOMES = [("not_run", "script not run", "white"), ("modified_no_harm", "ran a modified copy, no harm", "black!12"),
            ("shipped_repaired", "ran as shipped, no harm at end", "black!32"), ("cleanup_blocked", "harm at end, cleanup refused", "black!60"),
            ("harm_left", "harm at end, no refused call", "black!90")]
HOST = {"claude_code": "CC", "opencode": "OC"}
GROUPS = [("adversarial", "Adversarial packages", [("claude_code", p) for p in ("default", "accept_edits", "skill_allowed", "skill_allowed_accept_edits")]
           + [("opencode", p) for p in ("default", "edits_denied", "edits_allowed")]),
          ("stealthy", "Disguised packages", [("claude_code", p) for p in ("skill_allowed", "skill_allowed_accept_edits")]
           + [("opencode", p) for p in ("edits_denied", "edits_allowed")])]
W, PITCH = 3.6, 0.34  # bar length for 100% and row pitch, cm


def cells(rows: list[dict]) -> dict:
    out: dict = collections.defaultdict(collections.Counter)
    for r in rows:
        if r["model"] == MODEL:
            out[(r["label"], r["runtime"], r["preset"])][r["end_state"]] += 1
    return out


def tikz(c: dict) -> str:
    esc = lambda s: s.replace("_", r"\_")
    t = [r"% Generated by tools/build_pilot_outcome_figure.py from results/agent-pilot/analysis.json; do not edit.",
         r"\begin{tikzpicture}[font=\scriptsize]"]
    y = 0.0
    t += [rf"\node[anchor=south,inner sep=1pt] at ({W * f:.2f},-0.14) {{{int(100 * f)}\%}};" for f in (0, 0.5, 1)]
    for label, title, bars in GROUPS:
        t.append(rf"\node[anchor=west,font=\scriptsize\bfseries] at (-4.3,{y:.2f}) {{{title}}};")
        y -= PITCH
        for host, preset in bars:
            k = c[(label, host, preset)]
            n = sum(k.values())
            assert n and set(k) <= {o for o, _, _ in OUTCOMES}, (label, host, preset, k)
            t.append(rf"\node[anchor=east] at (-0.08,{y:.2f}) {{{HOST[host]} \texttt{{{esc(preset)}}} ({n})}};")
            x = 0.0
            for o, _, fill in OUTCOMES:
                w = W * k[o] / n
                if w > 0:
                    t.append(rf"\fill[{fill},draw=black,line width=0.2pt] ({x:.3f},{y - 0.12:.2f}) rectangle ({x + w:.3f},{y + 0.12:.2f});")
                x += w
            y -= PITCH
        y -= 0.1
    for i, (_, name, fill) in enumerate(OUTCOMES):
        lx, ly = -4.3 + (i % 2) * 4.05, y - (i // 2) * PITCH
        t.append(rf"\fill[{fill},draw=black,line width=0.2pt] ({lx:.2f},{ly - 0.09:.2f}) rectangle ({lx + 0.25:.2f},{ly + 0.09:.2f});")
        t.append(rf"\node[anchor=west] at ({lx + 0.3:.2f},{ly:.2f}) {{{name}}};")
    t += [rf"\draw[line width=0.2pt] (0,-0.17) -- (0,{y + PITCH - 0.25:.2f});", r"\end{tikzpicture}", ""]
    return "\n".join(t)


def _selftest() -> None:
    c = cells([{"model": MODEL, "label": "adversarial", "runtime": "claude_code", "preset": "default", "end_state": "not_run"}])
    assert c[("adversarial", "claude_code", "default")]["not_run"] == 1 and not cells([{**{"model": "x"}, "label": "a", "runtime": "r", "preset": "p", "end_state": "o"}])


if __name__ == "__main__":
    _selftest()
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(tikz(cells(json.loads(SRC.read_text(encoding="utf-8"))["rows"])), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
